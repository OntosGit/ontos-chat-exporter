function Refresh-Path {
    $machine = [Environment]::GetEnvironmentVariable('PATH','Machine')
    $user = [Environment]::GetEnvironmentVariable('PATH','User')
    $links = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links'
    $extra = @($env:Path,$machine,$user,$links)
    if ($env:ProgramFiles) { $extra += (Join-Path $env:ProgramFiles 'WinGet\Links') }
    $env:Path = ($extra | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }) -join ';'
}
function Locate-Bw {
    $c = Get-Command bw -ErrorAction SilentlyContinue
    if ($null -ne $c -and $c.CommandType -in @('Application','ExternalScript')) { return [string]$c.Source }
    $locations = @(
        (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links\bw.exe'),
        (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links\bw.cmd'),
        (Join-Path $env:APPDATA 'npm\bw.cmd'),
        (Join-Path $env:USERPROFILE 'scoop\shims\bw.exe')
    )
    if ($env:ProgramFiles) { $locations += (Join-Path $env:ProgramFiles 'WinGet\Links\bw.exe') }
    foreach ($candidate in $locations) {
        if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
    }
    return $null
}
function Ensure-BwCli {
    Refresh-Path
    $bw = Locate-Bw
    if ([string]::IsNullOrWhiteSpace($bw)) {
        $winget = Get-Command winget.exe -ErrorAction SilentlyContinue
        if ($null -eq $winget) { throw 'Neither bw.exe nor winget.exe is installed. Install Microsoft App Installer (winget).' }
        Write-Host 'Bitwarden CLI missing; installing official Bitwarden.CLI with winget...' -ForegroundColor Cyan
        & $winget.Source install --id Bitwarden.CLI --exact --source winget --accept-package-agreements --accept-source-agreements
        if ($LASTEXITCODE -ne 0) { throw ('Bitwarden CLI winget install failed with code {0}' -f $LASTEXITCODE) }
        Refresh-Path
        $bw = Locate-Bw
    }
    if ([string]::IsNullOrWhiteSpace($bw)) { throw 'Bitwarden CLI installed but bw.exe not found. Open a new PowerShell and rerun.' }
    $env:Path = (Split-Path -Path $bw -Parent) + ';' + $env:Path
    Write-Host ('Bitwarden CLI: {0}' -f $bw) -ForegroundColor Green
    & $bw --version
    if ($LASTEXITCODE -ne 0) { throw 'Bitwarden CLI version check failed.' }
    $statusJSON = (& $bw status) -join "`n"
    if ($LASTEXITCODE -ne 0) { throw 'Bitwarden CLI status failed.' }
    $s = ConvertFrom-Json -InputObject $statusJSON
    if ([string]$s.status -eq 'unauthenticated') {
        Write-Host 'Bitwarden CLI requires a one-time login. Credentials are entered ONLY into official bw.exe.' -ForegroundColor Yellow
        Write-Host 'If you use EU vault, configure: bw config server https://vault.bitwarden.eu' -ForegroundColor Yellow
        & $bw login
        if ($LASTEXITCODE -ne 0) { throw 'Bitwarden CLI login failed or was cancelled.' }
        $statusJSON = (& $bw status) -join "`n"
        if ($LASTEXITCODE -ne 0) { throw 'Bitwarden CLI status after login failed.' }
        $s = ConvertFrom-Json -InputObject $statusJSON
    }
    if ([string]$s.status -notin @('locked','unlocked')) {
        throw ('Unexpected Bitwarden CLI status: {0}' -f $s.status)
    }
}

